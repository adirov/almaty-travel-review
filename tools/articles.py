#!/usr/bin/env python3
"""Articles (blog) for almaty-travel.kz with a draft / published flag.

Source: articles/<slug>.<lang>.md  (lang = en | ru). English is the main version, Russian is a copy.
Front matter (between --- lines, "key: value"):
    title, description, status (draft | published), date (YYYY-MM-DD), image (/assets/...), image_alt
Body: simple Markdown: "## heading", "### heading", "- list item", "1. item", paragraphs,
      **bold**, [link](/en/tours/), and site links written without the /almaty-travel-review prefix.

Pages go to /<lang>/guide/<slug>/ (the existing travel guide section) and are listed on the guide index
and in the "Articles" block on the home page.

Two modes:
  python3 tools/articles.py preview <repo>   review site (GitHub Pages, noindex): drafts are rendered too,
                                             with a yellow "DRAFT" banner, so Artur can read them first.
  build_live.py calls apply(page_map, ...)   public site: only status=published. Draft pages are removed,
                                             so they never reach almaty-travel.kz or its sitemap.
To publish: change "status: draft" to "status: published", run preview, commit, rebuild live.
"""
import html
import yaml
import json
import os
import re
import sys

TEMPLATE_SLUG = 'yurt-stay-kolsai'
LANGS = ('en', 'ru')
START, END = '<!--articles:start-->', '<!--articles:end-->'
GEN = '<!-- generated by tools/articles.py: edit articles/*.md, not this file -->'
UI = {
    'en': {'home': 'Home', 'guide': 'Travel guide', 'draft': 'DRAFT: not published. Visible only on the review site, not on almaty-travel.kz.',
           'by': 'Kazakhstan Travel', 'cta': 'Plan your private tour on WhatsApp', 'latest': 'Articles',
           'all': 'All articles', 'draft_tag': 'draft', 'months': ['January', 'February', 'March', 'April', 'May', 'June', 'July',
                                                                   'August', 'September', 'October', 'November', 'December']},
    'ru': {'home': 'Главная', 'guide': 'Гид', 'draft': 'ЧЕРНОВИК: не опубликовано. Видно только на демо-сайте, не на almaty-travel.kz.',
           'by': 'Kazakhstan Travel', 'cta': 'Обсудить частный тур в WhatsApp', 'latest': 'Статьи',
           'all': 'Все статьи', 'draft_tag': 'черновик', 'months': ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля',
                                                                    'августа', 'сентября', 'октября', 'ноября', 'декабря']},
}


def load(repo):
    """All articles: list of dicts (slug, lang, meta..., body_html)."""
    folder = os.path.join(repo, 'articles')
    out = []
    if not os.path.isdir(folder):
        return out
    for name in sorted(os.listdir(folder)):
        m = re.match(r'^([a-z0-9-]+)\.(en|ru)\.md$', name)
        if not m:
            continue
        with open(os.path.join(folder, name), encoding='utf-8') as fh:
            text = fh.read().replace('\r\n', '\n')
        fm = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
        if not fm:
            raise SystemExit('articles/%s: front matter (--- ... ---) is missing' % name)
        # YAML front matter (the admin panel writes quoted / folded values too)
        meta = {k: ('' if v is None else str(v).strip()) for k, v in (yaml.safe_load(fm.group(1)) or {}).items()}
        for key in ('title', 'description', 'status', 'date'):
            if not meta.get(key):
                raise SystemExit('articles/%s: "%s" is required' % (name, key))
        if meta['status'] not in ('draft', 'published'):
            raise SystemExit('articles/%s: status must be draft or published' % name)
        out.append(dict(meta, slug=m.group(1), lang=m.group(2), body=fm.group(2).strip()))
    out.sort(key=lambda a: a['date'], reverse=True)
    return out


def inline(s, base):
    """**bold**, _italic_, [link](/en/...), \\-escapes, <br> (same rules as the admin's page text)."""
    import cms
    return cms._inline_html(s, base)


def markdown(md, base):
    out, para, lst = [], [], None
    def flush():
        nonlocal para, lst
        if para:
            out.append('<p>%s</p>' % '<br>'.join(inline(re.sub(r'\s+', ' ', x).strip(), base) for x in re.split(r'(?:\\|  +)\n', '\n'.join(para))))
            para = []
        if lst:
            tag, items = lst
            out.append('<%s>%s</%s>' % (tag, ''.join('<li>%s</li>' % inline(i, base) for i in items), tag))
            lst = None
    n = 0
    for line in md.split('\n'):
        s = line.strip()
        h = re.match(r'^(#{2,3})\s+(.*)$', s)
        ul = re.match(r'^[-*]\s+(.*)$', s)
        ol = re.match(r'^\d+\.\s+(.*)$', s)
        if not s:
            flush()
        elif h:
            flush()
            lvl = len(h.group(1))
            ident = ' id="s-%d"' % n if lvl == 2 else ''
            n += lvl == 2
            out.append('<h%d%s>%s</h%d>' % (lvl, ident, inline(h.group(2), base), lvl))
        elif ul or ol:
            if para:
                flush()
            tag = 'ul' if ul else 'ol'
            if not lst or lst[0] != tag:
                flush()
                lst = (tag, [])
            lst[1].append((ul or ol).group(1))
        else:
            if lst:
                flush()
            para.append(s)
    flush()
    return ''.join(out)


def nice_date(d, lang):
    y, m, day = d.split('-')
    months = UI[lang]['months']
    return '%d %s %s' % (int(day), months[int(m) - 1], y)


def visible(articles, include_drafts):
    return [a for a in articles if include_drafts or a['status'] == 'published']


def render(a, tpl, host, base, langs_available):
    """Article page from the template guide page (same header, menu, footer, analytics)."""
    lang, slug = a['lang'], a['slug']
    ui = UI[lang]
    s = tpl.replace('/guide/%s/' % TEMPLATE_SLUG, '/guide/%s/' % slug)
    url = '%s/%s/guide/%s/' % (host, lang, slug)
    other = 'ru' if lang == 'en' else 'en'
    if other not in langs_available:
        s = re.sub(r'<link rel="alternate" hreflang="%s"[^>]*>' % other, '', s)
        s = s.replace('%s/%s/guide/%s/' % (base, other, slug), '%s/%s/guide/' % (base, other))
        s = re.sub(r'<link rel="alternate" hreflang="%s"[^>]*>' % lang, '', s)
    s = s.replace('%s/summer/%s/guide/%s/' % (base, lang, slug), '%s/summer/%s/guide/' % (base, lang))
    title = '%s | Kazakhstan Travel' % a['title']
    desc = a['description']
    s = re.sub(r'<title>[^<]*</title>', lambda m: '<title>%s</title>' % html.escape(title, quote=False), s, count=1)
    for attr, val in (('name="description"', desc), ('property="og:title"', title), ('property="og:description"', desc),
                      ('name="twitter:title"', title), ('name="twitter:description"', desc)):
        s = re.sub(r'(<meta %s content=")[^"]*' % attr, lambda m, v=val: m.group(1) + html.escape(v), s)
    img = a.get('image')
    if img:
        s = re.sub(r'(<meta property="og:image" content=")[^"]*', lambda m: m.group(1) + 'https://www.almaty-travel.kz' + img, s)
        s = re.sub(r'<meta property="og:image:(width|height)" content="[^"]*">\s*', '', s)
        s = re.sub(r'(<meta property="og:image:alt" content=")[^"]*', lambda m: m.group(1) + html.escape(a.get('image_alt', '')), s)
    if a['status'] == 'draft' and 'name="robots"' not in s:
        s = s.replace('</head>', '<meta name="robots" content="noindex, nofollow">\n</head>', 1)
    ld = {'@context': 'https://schema.org', '@graph': [
        {'@type': 'BreadcrumbList', 'itemListElement': [
            {'@type': 'ListItem', 'position': 1, 'name': ui['home'], 'item': '%s/%s' % (host, '' if lang == 'ru' and base == '' else lang + '/')},
            {'@type': 'ListItem', 'position': 2, 'name': ui['guide'], 'item': '%s/%s/guide/' % (host, lang)},
            {'@type': 'ListItem', 'position': 3, 'name': a['title'], 'item': url}]},
        dict({'@type': 'Article', '@id': url + '#article', 'mainEntityOfPage': url, 'headline': a['title'], 'description': desc,
              'inLanguage': lang, 'datePublished': a['date'], 'dateModified': a.get('updated', a['date']),
              'author': {'@type': 'Organization', 'name': 'Kazakhstan Travel', 'url': 'https://www.almaty-travel.kz/'},
              'publisher': {'@id': 'https://www.almaty-travel.kz/#organization'}},
             **({'image': 'https://www.almaty-travel.kz' + img} if img else {}))]}
    s = re.sub(r'<script type="application/ld\+json">.*?</script>',
               lambda m: '<script type="application/ld+json">%s</script>' % json.dumps(ld, ensure_ascii=False), s, count=1, flags=re.S)
    body = markdown(a['body'], base)
    toc = re.findall(r'<h2 id="(s-\d+)">(.*?)</h2>', body)
    parts = ['<nav class="almaty-breadcrumbs"><a href="%s/%s/">%s</a> / <a href="%s/%s/guide/">%s</a></nav>' % (base, lang, ui['home'], base, lang, ui['guide'])]
    if a['status'] == 'draft':
        parts.append('<p class="article-draft" role="note">%s</p>' % ui['draft'])
    parts.append('<h1>%s</h1>' % html.escape(a['title'], quote=False))
    parts.append('<p class="guide-meta">%s · <time datetime="%s">%s</time></p>' % (ui['by'], a['date'], nice_date(a['date'], lang)))
    parts.append('<p class="guide-summary">%s</p>' % html.escape(desc, quote=False))
    if img:
        parts.append('<img class="guide-photo" src="%s%s" alt="%s" loading="lazy" decoding="async">' % (base, img, html.escape(a.get('image_alt', ''))))
    if len(toc) > 2:
        parts.append('<nav aria-label="Contents"><ul>%s</ul></nav>' % ''.join('<li><a href="#%s">%s</a></li>' % t for t in toc))
    parts.append(body)
    parts.append('<p class="guide-cta"><a href="https://wa.me/77775259885">%s</a></p>' % ui['cta'])
    main = ''.join(parts)
    s = re.sub(r'(<div class="main_container geo-guide">).*?(</div><div id="center_footer">)', lambda m: m.group(1) + GEN + main + m.group(2), s, count=1, flags=re.S)
    return s


def cards(arts, base, lang, home=False):
    ui = UI[lang]
    if home:
        items = ''.join('<li><a href="%s/%s/guide/%s/">%s</a>%s</li>' % (base, lang, a['slug'], html.escape(a['title'], quote=False),
                        ' <small class="article-tag">%s</small>' % ui['draft_tag'] if a['status'] == 'draft' else '') for a in arts[:3])
        return '%s<div class="home-articles"><h3>%s</h3><ul>%s</ul></div>%s' % (START, ui['latest'], items, END)
    out = ''.join('<section class="guide-card"><h2><a href="%s/%s/guide/%s/">%s</a>%s</h2><p>%s</p></section>' % (
        base, lang, a['slug'], html.escape(a['title'], quote=False),
        ' <small class="article-tag">%s</small>' % ui['draft_tag'] if a['status'] == 'draft' else '',
        html.escape(a['description'], quote=False)) for a in arts)
    return START + out + END


def put_block(s, block, anchor_re):
    if START in s:
        return re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda m: block, s, count=1, flags=re.S)
    m = re.search(anchor_re, s, re.S)
    if not m:
        return s
    return s[:m.start()] + block + s[m.start():]


def apply(pages, articles, host, base, include_drafts):
    """pages: dict rel -> html. Adds/updates article pages, guide index and home blocks. Returns removed rels."""
    removed = []
    shown = visible(articles, include_drafts)
    for a in articles:
        rel = '%s/guide/%s/index.html' % (a['lang'], a['slug'])
        if a not in shown:
            if rel in pages and GEN in pages[rel]:
                pages.pop(rel)
                removed.append(rel)
            continue
        tpl = pages['%s/guide/%s/index.html' % (a['lang'], TEMPLATE_SLUG)]
        langs = {x['lang'] for x in shown if x['slug'] == a['slug']}
        pages[rel] = render(a, tpl, host, base, langs)
    for lang in LANGS:
        arts = [a for a in shown if a['lang'] == lang]
        idx = '%s/guide/index.html' % lang
        if idx in pages:
            s = put_block(pages[idx], cards(arts, base, lang), r'<section class="guide-card">')
            # CollectionPage.hasPart: our articles first
            def part(m):
                data = json.loads(m.group(1))
                for node in data.get('@graph', []):
                    if node.get('@type') == 'CollectionPage':
                        keep = [p for p in node.get('hasPart', []) if not p.get('_gen')]
                        keep = [p for p in keep if not any(p.get('url', '').endswith('/guide/%s/' % x['slug']) for x in articles)]
                        node['hasPart'] = [{'@type': 'Article', 'url': '%s/%s/guide/%s/' % (host, lang, x['slug']), 'name': x['title']}
                                           for x in arts if x['status'] == 'published'] + keep
                return '<script type="application/ld+json">%s</script>' % json.dumps(data, ensure_ascii=False)
            s = re.sub(r'<script type="application/ld\+json">(.*?)</script>', part, s, count=1, flags=re.S)
            pages[idx] = s
        # RU home is also copied to the domain root in the live build ('index.html')
        for home in ['%s/index.html' % lang] + (['index.html'] if lang == 'ru' else []):
            if home in pages and arts:
                pages[home] = put_block(pages[home], cards(arts, base, lang, home=True), r'</section>(?=</div>\s*<div id="center_footer">)')
            elif home in pages and START in pages[home]:
                pages[home] = re.sub(re.escape(START) + r'.*?' + re.escape(END), '', pages[home], flags=re.S)
    return removed


def preview(repo):
    pages = {}
    rels = ['%s/guide/%s/index.html' % (l, TEMPLATE_SLUG) for l in LANGS] + ['%s/guide/index.html' % l for l in LANGS] + ['%s/index.html' % l for l in LANGS]
    articles = load(repo)
    rels += ['%s/guide/%s/index.html' % (a['lang'], a['slug']) for a in articles]
    for rel in rels:
        p = os.path.join(repo, rel)
        if os.path.exists(p):
            with open(p, encoding='utf-8', newline='') as fh:
                pages[rel] = fh.read()
    before = dict(pages)
    removed = apply(pages, articles, 'https://adirov.github.io/almaty-travel-review', '/almaty-travel-review', include_drafts=True)
    for rel, s in pages.items():
        if before.get(rel) != s:
            p = os.path.join(repo, rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, 'w', encoding='utf-8', newline='') as fh:
                fh.write(s)
            print('wrote', rel)
    for rel in removed:
        os.remove(os.path.join(repo, rel))
    print('articles:', ', '.join('%s.%s (%s)' % (a['slug'], a['lang'], a['status']) for a in articles) or 'none')


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == 'preview':
        preview(sys.argv[2])
    else:
        print(__doc__)
