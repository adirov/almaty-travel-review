def _dims(repo, url):
    try:
        from PIL import Image
        with Image.open(os.path.join(repo, url.lstrip('/'))) as im:
            return im.size
    except Exception:
        return None


def _small(repo, url):
    """640px copy for the grid thumbnail; made here for new uploads when Pillow is available."""
    stem, ext = os.path.splitext(url)
    for cand in (stem + '-640' + ext, stem + '-640.webp'):
        if os.path.isfile(os.path.join(repo, cand.lstrip('/'))):
            return cand
    src = os.path.join(repo, url.lstrip('/'))
    if not os.path.isfile(src) or ext.lower() not in ('.jpg', '.jpeg', '.png', '.webp'):
        return None
    try:
        from PIL import Image
        with Image.open(src) as im:
            if im.width <= 700:
                return None
            im = im.convert('RGB')
            im = im.resize((640, round(im.height * 640 / im.width)), Image.LANCZOS)
            dst = stem + '-640.webp'
            im.save(os.path.join(repo, dst.lstrip('/')), 'WEBP', quality=82)
            return dst
    except Exception:
        return None


def item_html(repo, image, alt, base, old):
    prev = old.get(image)
    if prev:
        return re.sub(r'(\salt=")[^"]*(")', lambda m: m.group(1) + html.escape(alt) + m.group(2), prev, count=1)
    small = _small(repo, image)
    wh = _dims(repo, image)
    img = '<img src="%s%s"' % (base, small or image)
    if small and wh:
        img += ' srcset="%s%s 640w, %s%s %dw" sizes="(max-width:600px) 45vw, 300px"' % (base, small, base, image, wh[0])
    if wh:
        img += ' width="%d" height="%d"' % wh
    img += ' alt="%s" loading="lazy" decoding="async">' % html.escape(alt)
    return '<a href="%s%s" target="_blank" rel="noopener">%s</a>' % (base, image, img)


def grid_html(repo, items, base, old, cls='owner-photo-grid tour-photos'):
    if not items:
        return ''
    return '<div class="%s">%s</div>' % (cls, ''.join(item_html(repo, i, a, base, old) for i, a in items))


def gallery_html(repo, g, lang, base, old, open_tag=None):
    if not g['photos'] and not g['more']:
        return ''
    title = g['title'] or MORE_LABEL[lang]
    if open_tag:
        open_tag = re.sub(r'(\saria-label=")[^"]*(")', lambda m: m.group(1) + html.escape(title) + m.group(2), open_tag)
    else:
        open_tag = '<section id="%s" class="%s" aria-label="%s">' % (g['id'], g['id'], html.escape(title))
    s = open_tag + '<h2>%s</h2>' % html.escape(title, quote=False)
    s += grid_html(repo, g['photos'] or g['more'], base, old)
    if g['photos'] and g['more']:
        label = g['more_label'] or MORE_LABEL[lang]
        s += '<details><summary>%s (%d)</summary>%s</details>' % (html.escape(label, quote=False), len(g['more']),
                                                               grid_html(repo, g['more'], base, old))
    return s + '</section>'


def set_head(s, title=None, desc=None, h1=None):
    """Title/description/H1 in the page (and og/twitter copies). Only changes what differs."""
    if title is not None:
        t = re.search(r'<title>(.*?)</title>', s, re.S)
        if t and html.unescape(t.group(1)).strip() != title:
            s = s[:t.start()] + '<title>%s</title>' % html.escape(title, quote=False) + s[t.end():]
            for attr in ('property="og:title"', 'name="twitter:title"'):
                s = re.sub(r'(<meta %s content=")[^"]*' % attr, lambda m: m.group(1) + html.escape(title), s)
    if desc is not None:
        d = re.search(r'<meta name="description" content="([^"]*)"', s)
        if d and html.unescape(d.group(1)).strip() != desc:
            for attr in ('name="description"', 'property="og:description"', 'name="twitter:description"'):
                s = re.sub(r'(<meta %s content=")[^"]*' % attr, lambda m: m.group(1) + html.escape(desc), s)
    if h1 is not None:
        h = re.search(r'<h1([^>]*)>(.*?)</h1>', s, re.S)
        if h and html.unescape(re.sub(r'<[^>]+>', '', h.group(2))).strip() != h1:
            s = s[:h.start()] + '<h1%s>%s</h1>' % (h.group(1), html.escape(h1, quote=False)) + s[h.end():]
    return s


def render(repo, s, fm, lang, base):
    """Write the content file data into one page. Returns the new HTML (unchanged when nothing differs)."""
    page = read_page(s)
    edits = []  # (start, end, new) on the original string, applied from the end
    old = {}
    for p in page['photos']:
        old[p['image']] = p['html']
    for g in page['galleries']:
        for p in g['photos'] + g['more']:
            old.setdefault(p['image'], p['html'])

    # text + photos inside the text
    if not fm.get('text_locked') and page['body'] is not None and '_span' in page:
        want_photos = _norm_photos(fm.get('photos'))
        have_photos = [(p['image'], p['alt']) for p in page['photos']]
        grids = [b for b in page['_blocks'] if b['tag'] == 'div']
        cls = _attr(grids[0]['attrs'], 'class') if grids else 'owner-photo-grid'
        body = fm.get('body') or ''
        if md_html(body, '', 'G') != md_html(page['body'], '', 'G') or want_photos != have_photos:
            grid = grid_html(repo, want_photos, base, old, cls)
            new = md_html(body, base, grid)
            if want_photos and MARK not in re.sub(r'\\(.)', r'\1', body):
                new += grid
            a, b = page['_span']
            edits.append((a, b, new))

    # galleries: matched by id; removed when deleted in the admin; new ones go after the last one
    want = _norm_galleries(fm.get('galleries'))
    by_id = {g['id']: g for g in want if g['id']}
    for g in page['galleries']:
        w = by_id.get(g['id'])
        have = {'id': g['id'], 'title': g['title'], 'photos': [(p['image'], p['alt']) for p in g['photos']],
                'more_label': g['more_label'], 'more': [(p['image'], p['alt']) for p in g['more']]}
        if w is None:
            edits.append((g['_span'][0], g['_span'][1], ''))
        elif w != have:
            edits.append((g['_span'][0], g['_span'][1], gallery_html(repo, w, lang, base, old, g['_open'])))
    known = {g['id'] for g in page['galleries']}
    new_g = [g for g in want if not g['id'] or g['id'] not in known]
    if new_g:
        if page['galleries']:
            at = page['galleries'][-1]['_span'][1]
        elif '_span' in page:
            at = page['_span'][1]
        else:
            at = None
        if at is not None:
            used = set(known) | {g['id'] for g in want if g['id']}
            add = ''
            for n, g in enumerate(new_g, 1):
                if not g['id']:
                    i = n
                    while 'owner-cms%d-photos' % i in used:
                        i += 1
                    g['id'] = 'owner-cms%d-photos' % i
                    used.add(g['id'])
                add += gallery_html(repo, g, lang, base, old)
            edits.append((at, at, add))

    for a, b, new in sorted(edits, key=lambda e: e[0], reverse=True):
        s = s[:a] + new + s[b:]
    return set_head(s, _s(fm.get('title')) or None, _s(fm.get('description')) or None, _s(fm.get('h1')) or None)


