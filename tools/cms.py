# ---------------------------------------------------------------- pages

def discover(repo):
    """[(lang, key, rel, section)] for every page the admin can edit."""
    out = []
    for lang in LANGS:
        out.append((lang, 'home', '%s/index.html' % lang, 'home'))
        for sub in ('private-tours', 'tours', 'winter'):
            d = os.path.join(repo, lang, sub)
            for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
                if os.path.isfile(os.path.join(d, name, 'index.html')):
                    out.append((lang, '%s--%s' % (sub, name), '%s/%s/%s/index.html' % (lang, sub, name), sub))
        d = os.path.join(repo, lang, 'pages')
        for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
            m = re.match(r'^(\d+)\.html$', name)
            if m:
                out.append((lang, 'pages--' + m.group(1), '%s/pages/%s' % (lang, name), 'pages'))
    return [p for p in out if p[1] not in EXCLUDE]


def read(path):
    with open(path, encoding='utf-8', newline='') as fh:
        return fh.read()


def write(path, s):
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        fh.write(s)


# ---------------------------------------------------------------- markdown <-> html

def _attr(attrs, name):
    m = re.search(r'\b%s="([^"]*)"' % name, attrs)
    return html.unescape(m.group(1)) if m else None


def _strip_base(url):
    return url[len(BASE):] if url.startswith(BASE + '/') else url


def _esc_md(text):
    return re.sub(r'([\\*_\[\]`<>])', r'\\\1', text)


def inline_md(frag):
    """Inline HTML (strong/b/em/i/a/br/span) -> Markdown. Raises Locked on anything else."""
    toks = []
    pos = 0
    for m in re.finditer(r'<(/?)([a-zA-Z0-9]+)([^>]*)>', frag):
        toks.append(('t', frag[pos:m.start()]))
        close, tag, attrs = m.group(1), m.group(2).lower(), m.group(3)
        if tag in ('strong', 'b'):
            toks.append(('m', '**'))
        elif tag in ('em', 'i'):
            toks.append(('m', '_'))
        elif tag == 'br':
            toks.append(('br', ''))
        elif tag == 'a':
            if close:
                toks.append(('aclose', ''))
            else:
                href = _attr(attrs, 'href')
                extra = re.sub(r'\s*\b(href|target|rel|title)="[^"]*"', '', attrs).strip(' /')
                if not href or extra:
                    raise Locked('link ' + attrs)
                toks.append(('aopen', _strip_base(href)))
        elif tag == 'span' and not attrs.strip():
            continue
        else:
            raise Locked('<%s%s>' % (tag, attrs))
        pos = m.end()
    toks.append(('t', frag[pos:]))
    out, href = [], []
    for kind, val in toks:
        if kind == 't':
            out.append(_esc_md(re.sub(r'[ \t\r\n]+', ' ', html.unescape(val))))
        elif kind == 'br':
            out.append('\x03')
        elif kind == 'aopen':
            href.append(val)
            out.append('[')
        elif kind == 'aclose':
            out.append('](%s)' % (href.pop() if href else ''))
        else:
            out.append('\x01' if val == '**' else '\x02')
    s = ''.join(out)
    for mark in ('\x01', '\x02'):  # spaces just inside a pair go outside; empty pairs vanish
        s = re.sub(mark + r'([^' + mark + r']*)' + mark,
                   lambda m: (' ' if m.group(1)[:1] == ' ' else '') + (mark + m.group(1).strip(' ') + mark if m.group(1).strip(' ') else '')
                   + (' ' if m.group(1)[-1:] == ' ' and m.group(1).strip(' ') else ''), s)
    s = re.sub(r' *\x03 *', '\x03', s)
    s = re.sub(r'  +', ' ', s).strip(' ')
    return s.replace('\x01', '**').replace('\x02', '_').replace('\x03', '\\\n')


def _line_start_escape(s):
    return re.sub(r'^([#>+\-]|\d+[.)])', lambda m: '\\' + m.group(1) if not m.group(1)[0].isdigit()
                  else m.group(1)[:-1] + '\\' + m.group(1)[-1], s)


def span_md(blocks):
    """Text blocks (from scan_span) -> Markdown. Raises Locked when not representable."""
    parts = []
    grids = 0
    for b in blocks:
        tag, attrs, inner = b['tag'], b['attrs'], b['inner']
        if tag == 'div':
            grids += 1
            if grids > 1:
                raise Locked('two photo grids in the text')
            parts.append(MARK)
        elif tag == 'p':
            cls = _attr(attrs, 'class')
            if re.sub(r'\s*class="[^"]*"', '', attrs).strip() or cls not in (None, TOUR_INTRO):
                raise Locked('<p%s>' % attrs)
            text = _line_start_escape(inline_md(inner))
            if not text.strip():  # spacer paragraphs (&nbsp;)
                continue
            parts.append(('> ' + text.replace('\\\n', '\\\n> ')) if cls == TOUR_INTRO else text)
        elif tag in ('h2', 'h3', 'h4'):
            if attrs.strip():
                raise Locked('<%s%s>' % (tag, attrs))
            parts.append('#' * int(tag[1]) + ' ' + inline_md(inner))
        else:  # ul / ol
            if attrs.strip():
                raise Locked('<%s%s>' % (tag, attrs))
            items = re.findall(r'<li>(.*?)</li>', inner, re.S)
            rest = re.sub(r'<li>.*?</li>', '', inner, flags=re.S).strip()
            if rest or not items:
                raise Locked('list markup')
            lines = []
            for n, it in enumerate(items, 1):
                t = inline_md(it).replace('\\\n', ' ')
                lines.append(('- ' if tag == 'ul' else '%d. ' % n) + t)
            parts.append('\n'.join(lines))
    return '\n\n'.join(parts)


def _inline_html(s, base):
    keep = []

    def hold(v):
        keep.append(v)
        return '\x00%d\x00' % (len(keep) - 1)
    s = re.sub(r'<br\s*/?>', lambda m: hold('<br>'), s)
    s = re.sub(r'\\([\\`*_{}\[\]()#+\-.!<>|~])', lambda m: hold(html.escape(m.group(1), quote=False)), s)
    s = html.escape(html.unescape(s), quote=False)

    def link(m):
        url = html.unescape(m.group(2))
        if url.startswith('/') and not url.startswith('//'):
            url = base + url
        return hold('<a href="%s">' % html.escape(url)) + m.group(1) + hold('</a>')
    s = re.sub(r'\[([^\]]+)\]\(\s*([^)\s]+)(?:\s+&quot;[^)]*&quot;)?\s*\)', link, s)
    s = re.sub(r'\*\*(?=\S)(.+?)(?<=\S)\*\*', r'<strong>\1</strong>', s)
    s = re.sub(r'__(?=\S)(.+?)(?<=\S)__', r'<strong>\1</strong>', s)
    s = re.sub(r'(?<![\w*])\*(?=\S)(.+?)(?<=\S)\*(?![\w*])', r'<em>\1</em>', s)
    s = re.sub(r'(?<![\w])_(?=\S)(.+?)(?<=\S)_(?![\w])', r'<em>\1</em>', s)
    return re.sub(r'\x00(\d+)\x00', lambda m: keep[int(m.group(1))], s)


def md_html(md, base, grid_html=''):
    """Markdown (as written by the admin) -> HTML blocks. MARK becomes the photo grid."""
    out, para, lst, quote = [], [], None, False

    def flush():
        nonlocal para, lst, quote
        if para:
            text = ''
            for i, line in enumerate(para):
                hard = line.endswith('\\') or line.endswith('  ')
                line = line[:-1] if line.endswith('\\') else line.rstrip()
                text += _inline_html(line.strip(), base) + (('<br>' if hard else ' ') if i < len(para) - 1 else '')
            if text:
                out.append('<p class="%s">%s</p>' % (TOUR_INTRO, text) if quote else '<p>%s</p>' % text)
        if lst:
            tag, items = lst
            out.append('<%s>%s</%s>' % (tag, ''.join('<li>%s</li>' % _inline_html(i, base) for i in items), tag))
        para, lst, quote = [], None, False

    for raw in md.replace('\r\n', '\n').split('\n'):
        line = raw.rstrip('\n')
        st = line.strip()
        h = re.match(r'^(#{1,4})\s+(.*?)\s*#*$', st)
        ul = re.match(r'^[-*+]\s+(.*)$', st)
        ol = re.match(r'^\d+[.)]\s+(.*)$', st)
        q = re.match(r'^>\s?(.*)$', st)
        if not st:
            flush()
        elif re.sub(r'\\(.)', r'\1', st) == MARK:
            flush()
            out.append(grid_html)
        elif h:
            flush()
            lvl = max(2, len(h.group(1)))
            out.append('<h%d>%s</h%d>' % (lvl, _inline_html(h.group(2), base), lvl))
        elif ul or ol:
            tag = 'ul' if ul else 'ol'
            if para or (lst and lst[0] != tag):
                flush()
            if not lst:
                lst = (tag, [])
            lst[1].append((ul or ol).group(1))
        elif q:
            if not quote:
                flush()
                quote = True
            para.append(q.group(1))
        else:
            if lst or quote:
                flush()
            para.append(line)
    flush()
    return ''.join(x for x in out if x)


# ---------------------------------------------------------------- reading pages

BLOCK = re.compile(r'\s*<(p|h2|h3|h4|ul|ol|div)\b([^>]*)>', re.I)


def scan_span(s, pos):
    """Plain text blocks right after </h1>: p, h2-h4, ul/ol and one owner photo grid."""
    blocks, i = [], pos
    while True:
        t = BLOCK.match(s, i)
        if not t:
            break
        tag, attrs = t.group(1).lower(), t.group(2)
        cls = _attr(attrs, 'class') or ''
        if tag == 'p' and 'owner-contact-cta' in cls:
            break
        if tag == 'div' and not cls.startswith('owner-photo-grid'):
            break
        if tag in ('ul', 'ol'):
            depth, j = 1, t.end()
            for m in re.finditer(r'<(/?)(?:ul|ol)\b[^>]*>', s[t.end():]):
                depth += -1 if m.group(1) else 1
                if not depth:
                    j = t.end() + m.end()
                    break
            else:
                break
            end, close = t.end() + (j - t.end()) - len('</%s>' % tag), j
        else:
            end = s.find('</%s>' % tag, t.end())
            if end < 0:
                break
            close = end + len('</%s>' % tag)
        inner = s[t.end():end]
        if tag == 'p' and re.search(r'<(p|div|section|table)\b', inner):
            break
        blocks.append({'tag': tag, 'attrs': attrs, 'inner': inner, 'start': t.start() + len(t.group(0)) - len(t.group(0).lstrip()), 'end': close})
        i = close
    return blocks


SECTION = re.compile(r'<section id="(owner-[a-z0-9-]*photos)"([^>]*)>(.*?)</section>', re.S)
GRID = re.compile(r'<div class="owner-photo-grid[^"]*">(.*?)</div>', re.S)
ITEM = re.compile(r'<a href="([^"]+)"[^>]*>(<img[^>]*>)</a>')


def grid_items(inner):
    items = []
    for m in ITEM.finditer(inner):
        items.append({'image': _strip_base(html.unescape(m.group(1))), 'alt': _attr(m.group(2), 'alt') or '', 'html': m.group(0)})
    if re.sub(r'\s+', '', ITEM.sub('', inner)):
        raise Locked('grid markup')
    return items


def parse_gallery(m):
    inner = m.group(3)
    h2 = re.match(r'\s*<h2>(.*?)</h2>\s*<div class="owner-photo-grid[^"]*">(.*?)</div>\s*', inner, re.S)
    if not h2:
        raise Locked('gallery head')
    rest = inner[h2.end():]
    more, label = [], ''
    if rest.strip():
        d = re.match(r'<details><summary>(.*?)</summary>\s*<div class="owner-photo-grid[^"]*">(.*?)</div>\s*</details>\s*$', rest, re.S)
        if not d:
            raise Locked('gallery tail')
        more = grid_items(d.group(2))
        label = re.sub(r'\s*\(\d+\)\s*$', '', html.unescape(d.group(1)).strip())
    return {'id': m.group(1), 'title': html.unescape(re.sub(r'<[^>]+>', '', h2.group(1))).strip(),
            'photos': grid_items(h2.group(2)), 'more_label': label, 'more': more}


def read_page(s):
    """Everything the admin can edit on one page, plus where it sits in the HTML."""
    t = re.search(r'<title>(.*?)</title>', s, re.S)
    d = re.search(r'<meta name="description" content="([^"]*)"', s)
    h = re.search(r'<h1([^>]*)>(.*?)</h1>', s, re.S)
    page = {
        'title': html.unescape(t.group(1)).strip() if t else '',
        'description': html.unescape(d.group(1)).strip() if d else '',
        'h1': html.unescape(re.sub(r'<[^>]+>', '', h.group(2))).strip() if h else '',
        'body': None, 'photos': [], 'galleries': [], 'locked_reason': '',
    }
    if h:
        blocks = scan_span(s, h.end())
        page['_span'] = (h.end(), blocks[-1]['end'] if blocks else h.end())
        page['_blocks'] = blocks
        try:
            page['body'] = span_md(blocks)
            grids = [b for b in blocks if b['tag'] == 'div']
            page['photos'] = grid_items(grids[0]['inner']) if grids else []
        except Locked as e:
            page['body'], page['locked_reason'] = None, str(e)
    for m in SECTION.finditer(s):
        try:
            g = parse_gallery(m)
        except Locked:
            continue
        g['_span'] = (m.start(), m.end())
        g['_open'] = s[m.start():m.start() + len('<section id="%s"' % m.group(1)) + len(m.group(2)) + 1]
        page['galleries'].append(g)
    return page


# ---------------------------------------------------------------- content files

def content_path(repo, lang, key):
    return os.path.join(repo, CONTENT, lang, key + '.md')


def _photos_out(items):
    return [{'image': p['image'], 'alt': p['alt']} for p in items]


def dump(lang, key, rel, section, page, locked):
    fm = {
        'page': rel,
        'url': '/' + (rel[:-len('index.html')] if rel.endswith('index.html') else rel),
        'section': SECTIONS[section][lang],
        'title': page['title'],
        'description': page['description'],
        'h1': page['h1'],
        'text_locked': locked,
        'photos': _photos_out(page['photos']),
        'galleries': [{'id': g['id'], 'title': g['title'], 'photos': _photos_out(g['photos']),
                       'more_label': g['more_label'], 'more': _photos_out(g['more'])} for g in page['galleries']],
    }
    head = yaml.safe_dump(fm, allow_unicode=True, sort_keys=False, width=10000, default_flow_style=False)
    return '---\n%s---\n%s\n' % (head, '' if locked else (page['body'] or ''))


def load(path):
    text = read(path).replace('\r\n', '\n')
    m = re.match(r'^---\n(.*?)\n---\n?(.*)$', text, re.S)
    if not m:
        raise SystemExit('%s: front matter (--- ... ---) is missing' % path)
    fm = yaml.safe_load(m.group(1)) or {}
    fm['body'] = m.group(2).strip('\n')
    return fm


def _norm_photos(items):
    out = []
    for p in items or []:
        if isinstance(p, dict) and (p.get('image') or '').strip():
            out.append(((p.get('image') or '').strip(), (p.get('alt') or '').strip()))
    return out


def _norm_galleries(gs):
    out = []
    for g in gs or []:
        if not isinstance(g, dict):
            continue
        out.append({'id': (g.get('id') or '').strip(), 'title': str(g.get('title') or '').strip(),
                    'photos': _norm_photos(g.get('photos')), 'more_label': str(g.get('more_label') or '').strip(),
                    'more': _norm_photos(g.get('more'))})
    return out


def _s(v):
    return re.sub(r'\s+', ' ', str(v if v is not None else '')).strip()


