#!/usr/bin/env python3
"""Bridge between the admin panel (Sveltia CMS, /admin/) and the rendered HTML pages.

The site is a snapshot of ready HTML pages (no template engine), so the admin edits small content
files and this script writes them into the pages:

    content/pages/<lang>/<key>.md   one file per page: SEO title, description, H1, main text
                                    (Markdown body), photos in the text and photo galleries

Commands:
    python3 tools/cms.py export <repo>              HTML -> content files (writes only what differs)
    python3 tools/cms.py apply  <repo> [files...]   content files -> HTML (only parts that differ;
                                                    no files = every content file)
build_live.py calls apply_live(page_map, repo) last, so titles/descriptions/H1 from the admin win
over the older hard-coded SEO patches on the public build.

Rules that keep it safe:
- a page part (title, description, H1, text, each gallery) is rewritten only when the content file
  differs from what the page already shows, so untouched pages stay byte-for-byte the same;
- the GitHub Action applies only the content files changed by a push, then runs export, so changes
  made in code (other tools/*.py) flow back into the content files instead of being reverted;
- text that cannot be expressed in simple Markdown (tables, inline styles, legacy layouts) is
  marked text_locked: the admin can still edit SEO fields and photos there, not the text.
Files are read and written with newline='' (the repo keeps CRLF in the HTML files).
"""
