def export(repo, quiet=False):
    """Content files from the HTML. A file is rewritten only when the page shows something else."""
    n = 0
    for lang, key, rel, section in discover(repo):
        page = read_page(read(os.path.join(repo, rel)))
        locked = key in LOCK_TEXT or not page['body']
        path = content_path(repo, lang, key)
        if os.path.isfile(path):
            fm = load(path)
            same = (fm.get('page') == rel and bool(fm.get('text_locked')) == locked
                    and _s(fm.get('title')) == _s(page['title']) and _s(fm.get('description')) == _s(page['description'])
                    and _s(fm.get('h1')) == _s(page['h1'])
                    and _norm_photos(fm.get('photos')) == [(p['image'], p['alt']) for p in page['photos']]
                    and _norm_galleries(fm.get('galleries')) == _norm_galleries(dump_galleries(page))
                    and (locked or md_html(fm.get('body') or '', '', 'G') == md_html(page['body'] or '', '', 'G')))
            if same:
                continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write(path, dump(lang, key, rel, section, page, locked))
        n += 1
        if not quiet:
            print('export', path, '(text locked: %s)' % page['locked_reason'] if locked and page['locked_reason'] else '')
    return n


def dump_galleries(page):
    return [{'id': g['id'], 'title': g['title'], 'photos': _photos_out(g['photos']),
             'more_label': g['more_label'], 'more': _photos_out(g['more'])} for g in page['galleries']]


def apply(repo, files=None):
    """Content files -> pages (+ their summer/ copies when those showed the same content)."""
    pages = {(lang, key): (rel, section) for lang, key, rel, section in discover(repo)}
    paths = []
    if files:
        paths = [f for f in files if os.path.isfile(os.path.join(repo, f)) and f.replace(os.sep, '/').startswith(CONTENT.replace(os.sep, '/') + '/')]
    else:
        for lang in LANGS:
            d = os.path.join(repo, CONTENT, lang)
            paths += [os.path.join(CONTENT, lang, f) for f in sorted(os.listdir(d)) if f.endswith('.md')] if os.path.isdir(d) else []
    changed = []
    for p in paths:
        m = re.search(r'([a-z]{2})[\\/]([^\\/]+)\.md$', p)
        if not m or (m.group(1), m.group(2)) not in pages:
            continue
        lang, key = m.group(1), m.group(2)
        rel = pages[(lang, key)][0]
        fm = load(os.path.join(repo, p))
        if key in LOCK_TEXT:
            fm['text_locked'] = True
        src = os.path.join(repo, rel)
        before = read(src)
        after = render(repo, before, fm, lang, BASE)
        if after == before:
            continue
        write(src, after)
        changed.append(rel)
        summer = os.path.join(repo, 'summer', rel)
        if os.path.isfile(summer):
            ss = read(summer)
            a, b = read_page(before), read_page(ss)
            if (a['body'], [(x['image'], x['alt']) for x in a['photos']], dump_galleries(a)) == \
               (b['body'], [(x['image'], x['alt']) for x in b['photos']], dump_galleries(b)):
                new = render(repo, ss, fm, lang, BASE)
                if new != ss:
                    write(summer, new)
                    changed.append('summer/' + rel)
            else:
                new = set_head(ss, _s(fm.get('title')) or None, _s(fm.get('description')) or None, _s(fm.get('h1')) or None)
                if new != ss:
                    write(summer, new)
                    changed.append('summer/' + rel)
    return changed


def apply_live(page_map, repo):
    """Public build: the admin's title/description/H1 are the last word (after the SEO patches)."""
    for lang, key, rel, section in discover(repo):
        path = content_path(repo, lang, key)
        if not os.path.isfile(path):
            continue
        fm = load(path)
        args = (_s(fm.get('title')) or None, _s(fm.get('description')) or None, _s(fm.get('h1')) or None)
        targets = [rel, 'summer/' + rel] + (['index.html'] if rel == 'ru/index.html' else []) + \
                  (['summer/index.html'] if rel == 'ru/index.html' else [])
        for r in targets:
            if r in page_map:
                page_map[r] = set_head(page_map[r], *args)
    return page_map


if __name__ == '__main__':
    if len(sys.argv) < 3 or sys.argv[1] not in ('export', 'apply'):
        raise SystemExit(__doc__)
    cmd, repo = sys.argv[1], sys.argv[2]
    if cmd == 'export':
        print('content files written:', export(repo))
    else:
        files = sys.argv[3:]
